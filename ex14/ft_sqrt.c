int	ft_sqrt(int nb)
{
	long	i;

	if (nb <= 0)
		return (0);
	if (nb == 1)
		return (1);
	i = 1;
	while (i * i <= nb && i <= 46340)
	{
		if (i * i == nb)
			return ((int)i);
		i++;
	}
	return (0);
}